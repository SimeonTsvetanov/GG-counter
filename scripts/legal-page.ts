/**
 * The standalone policy pages `{base}<page>/index.html` (app-shell → legal-pages §1, templates/pages):
 * real HTML from the same LegalDocument data as the in-app dialogs — readable without JavaScript,
 * printable, in the sitemap, precached by the service worker. Used by scripts/generate.ts.
 */
import type { AppConfig, ShellItemId } from "../app.config.ts";
import { en } from "../app/src/i18n/en.ts";
import { isPolicyPage, type LegalBlock, type LegalDocument, type LegalInline } from "../app/src/ui/legal-document.ts";
import { escapeHtml } from "./seo.ts";

/** The pages' stylesheet in app/public/ (copied from scripts/page-assets/ by generate.ts). */
export const POLICY_PAGE_CSS = "policy-page.css";
/** The pages' only script in app/public/ ({@link yearScript}, written by generate.ts). */
export const POLICY_PAGE_SCRIPT = "year.js";

/**
 * Returns the source of year.js (forge app-shell templates/pages/year.js): writes the current year
 * into `[data-year]` (never hard-coded, app-shell rule 3) and assembles the email of
 * `[data-email-user]` links, so the address is never plain text in the HTML.
 *
 * @remarks Plain ES5 in an external file: the pages' meta CSP forbids inline script.
 */
export function yearScript(): string {
  return `// Generated by scripts/generate.ts (scripts/legal-page.ts) — never edit. Year and contact email of the policy pages.
document.querySelectorAll("[data-year]").forEach(function (el) {
  el.textContent = String(new Date().getFullYear());
});
document.querySelectorAll("[data-email-user]").forEach(function (a) {
  var email = a.getAttribute("data-email-user") + "@" + a.getAttribute("data-email-domain");
  a.setAttribute("href", "mailto:" + email);
  a.textContent = email;
});
`;
}

/**
 * Meta CSP of the template page: only our own files; theme-init.js and year.js are external
 * scripts, so no inline script or style is needed.
 */
const CSP = "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; base-uri 'self'; object-src 'none'; form-action 'self'";

/** Returns the date the way the English page writes it: "19 November 2026". */
export function englishDate(isoDate: string): string {
  return new Date(`${isoDate}T00:00:00Z`).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });
}

/** Returns the email as an element year.js fills in: never plain text in HTML (anti-scraping, forge DECISIONS 2026-11-05). */
function emailHtml(app: AppConfig): string {
  const [user = "", domain = ""] = app.contact.email.split("@");
  return `<a data-email-user="${escapeHtml(user)}" data-email-domain="${escapeHtml(domain)}">email (needs JavaScript)</a>`;
}

/** Returns one run of text as HTML. */
function inlineHtml(app: AppConfig, inline: LegalInline): string {
  switch (inline.kind) {
    case "text":
      return escapeHtml(inline.text);
    case "strong":
      return `<strong>${escapeHtml(inline.text)}</strong>`;
    case "code":
      return `<code>${escapeHtml(inline.text)}</code>`;
    case "link":
      return `<a href="${escapeHtml(inline.href)}">${escapeHtml(inline.text)}</a>`;
    case "email":
      return emailHtml(app);
    default:
      return inline satisfies never;
  }
}

/** Returns the runs of a paragraph, heading or list item as HTML. */
function inlinesHtml(app: AppConfig, inlines: readonly LegalInline[]): string {
  return inlines.map((inline) => inlineHtml(app, inline)).join("");
}

/** Returns one block as HTML. */
function blockHtml(app: AppConfig, block: LegalBlock): string {
  switch (block.kind) {
    case "heading":
      return `<h2>${inlinesHtml(app, block.inlines)}</h2>`;
    case "paragraph":
      return `<p>${inlinesHtml(app, block.inlines)}</p>`;
    case "list": {
      const tag = block.isOrdered ? "ol" : "ul";
      return `<${tag}>${block.items.map((item) => `\n          <li>${inlinesHtml(app, item)}</li>`).join("")}\n        </${tag}>`;
    }
    default:
      return block satisfies never;
  }
}

/** Returns a footer entry of app.config.ts as a link of the static page, or null when it has no page. */
function footerLink(app: AppConfig, id: ShellItemId): string | null {
  const label = escapeHtml(en.shell.menu.items[id]);
  if (id === "support") return `<a href="${escapeHtml(app.shell.buyMeACoffee)}">${label}</a>`;
  const page = id === "contact" ? "support" : id;
  return isPolicyPage(page) ? `<a href="${app.basePath}${page}/">${label}</a>` : null;
}

/** Returns the page footer: the app footer's links in the same order (WCAG 3.2.6), © and the way back. */
function footerHtml(app: AppConfig): string {
  const links = app.shell.footer.map((id) => footerLink(app, id)).filter((link) => link !== null);
  return `<footer class="policy-footer">
      <nav class="policy-nav" aria-label="${escapeHtml(en.shell.footer)}">${links.join(" · ")}</nav>
      <p>© <span data-year>${String(new Date().getFullYear())}</span> ${escapeHtml(app.author.name)} · <a href="${app.basePath}">Back to ${escapeHtml(app.name)}</a></p>
    </footer>`;
}

/** Returns the head of a policy page: CSP, title, description, canonical, icon, style and scripts. */
function headHtml(app: AppConfig, doc: LegalDocument): string {
  const base = app.basePath;
  return `<meta http-equiv="Content-Security-Policy" content="${CSP}" />
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
    <meta name="referrer" content="strict-origin-when-cross-origin" />
    <meta name="theme-color" content="${app.manifest.themeColor}" />
    <title>${escapeHtml(doc.title)} · ${escapeHtml(app.name)}</title>
    <meta name="description" content="${escapeHtml(`${doc.title} of ${app.name}, the ${app.tagline.toLowerCase()}.`)}" />
    <link rel="canonical" href="${app.url}${doc.id}/" />
    <link rel="icon" href="${base}favicon.svg" />
    <link rel="stylesheet" href="${base}${POLICY_PAGE_CSS}" />
    <script src="${base}theme-init.js"></script>
    <script src="${base}${POLICY_PAGE_SCRIPT}" defer></script>`;
}

/** Returns the standalone HTML page of `doc` (English, like every policy page — app-shell → i18n §4). */
export function policyPageHtml(app: AppConfig, doc: LegalDocument): string {
  const body = doc.blocks.map((block) => blockHtml(app, block)).join("\n        ");
  return `<!doctype html>
<html lang="en">
  <head>
    ${headHtml(app, doc)}
  </head>
  <body>
    <header class="policy-header">
      <a class="policy-brand" href="${app.basePath}"><img src="${app.basePath}favicon.svg" alt="" width="28" height="28" /><span>${escapeHtml(app.name)}</span></a>
    </header>
    <main class="policy">
      <article class="policy-body">
        <h1>${escapeHtml(doc.title)}</h1>
        <p class="policy-updated">Last updated: ${englishDate(doc.updated)}</p>
        ${body}
      </article>
    </main>
    ${footerHtml(app)}
  </body>
</html>
`;
}
