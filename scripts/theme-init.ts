// Builds app/public/theme-init.js (written by generate.ts): a tiny blocking script in <head> that puts
// the saved theme's class on <html> before the first paint, so dark users see no light flash; a saved
// choice also sets `data-theme`, which design/tokens.css turns into the color-scheme (PLAN T-12). It
// mirrors the theme and migration rules of packages/miniapp/src/storage (theme.ts, migrate.ts; tests check).
import type { AppConfig } from "../app.config.ts";

/** The pre-forge theme key (SPEC §4): read only while the migration marker does not list the theme. */
export const LEGACY_THEME_KEY = "gg-counter-theme";

/**
 * Returns the source of theme-init.js for `config.id`.
 *
 * @remarks Plain ES5, no imports: it runs before the app bundle and as an external file because a
 * meta CSP forbids inline scripts. The new key wins; the old key is a fallback until migrated; an
 * unreadable value or blocked storage follows the system theme, like the theme provider.
 */
export function themeInitScript(config: Pick<AppConfig, "id">): string {
  const key = (name: string): string => JSON.stringify(`${config.id}:v1:${name}`);
  return `// Generated by scripts/generate.ts from app.config.ts — never edit. Sets the saved theme's class on
// <html> before the first paint (no flash) and data-theme for a saved choice (tokens.css: color-scheme);
// the React theme provider takes over after load.
(function () {
  var theme = null;
  try {
    var saved = localStorage.getItem(${key("theme")});
    if (saved !== null) {
      theme = JSON.parse(saved);
    } else {
      var marker = JSON.parse(localStorage.getItem(${key("migrated")}) || "null");
      var migrated = marker !== null && typeof marker === "object" && Array.isArray(marker.items) && marker.items.indexOf("theme") >= 0;
      if (!migrated) theme = localStorage.getItem(${JSON.stringify(LEGACY_THEME_KEY)});
    }
  } catch (e) {
    /* storage blocked or unreadable: follow the system theme */
  }
  if (theme === "light" || theme === "dark") {
    document.documentElement.setAttribute("data-theme", theme);
  } else {
    theme = window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
  }
  document.documentElement.classList.add(theme);
})();
`;
}
