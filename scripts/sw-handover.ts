// Builds app/public/sw-handover.js (written by generate.ts, loaded by the service worker through
// Workbox `importScripts`). PLAN T-08 switched the service worker from auto-update to "prompt": a new
// worker waits until the user taps Reload. Pages of the older builds cannot send that message (they
// have no update toast), so their copies would wait until every window closes. This script lets the
// new worker take over at once in exactly that case — the page is not reloaded; its next start runs
// the new version — and leaves every later update to the Reload toast (pwa §5, DECISIONS 2026-11-19).
import type { AppConfig } from "../app.config.ts";

/** File name of the generated script in app/public (also in vite.config.ts `importScripts`). */
export const SW_HANDOVER_FILE = "sw-handover.js";

/**
 * Returns the source of sw-handover.js for `config`.
 *
 * @remarks How an older worker is recognised: the auto-update builds precached `registerSW.js` (the
 * plugin's injected register script); builds since T-08 register from the bundle and have no such
 * file, and Workbox deletes it from the precache when the new worker activates — so only the first
 * update away from an auto-update build skips waiting. Plain ES5, no imports (service worker scope).
 */
export function swHandoverScript(config: Pick<AppConfig, "id" | "basePath">): string {
  return `// Generated by scripts/generate.ts from app.config.ts — never edit. Hands over from the pre-T-08
// auto-update service worker without waiting for all windows to close (scripts/sw-handover.ts).
(function () {
  var PRECACHE_PREFIX = ${JSON.stringify(`${config.id}-precache-`)};
  var OLD_REGISTER_PATH = ${JSON.stringify(`${config.basePath}registerSW.js`)};
  function hasOldRegisterScript(requests) {
    return requests.some(function (request) { return new URL(request.url).pathname === OLD_REGISTER_PATH; });
  }
  self.addEventListener("install", function (event) {
    event.waitUntil(
      caches.keys()
        .then(function (names) {
          var own = names.filter(function (name) { return name.indexOf(PRECACHE_PREFIX) === 0; });
          return Promise.all(own.map(function (name) { return caches.open(name).then(function (cache) { return cache.keys(); }); }));
        })
        .then(function (lists) {
          if (lists.some(hasOldRegisterScript)) return self.skipWaiting();
          return undefined;
        })
        .catch(function () {
          /* no cache access: wait for the Reload toast as usual */
        })
    );
  });
})();
`;
}
