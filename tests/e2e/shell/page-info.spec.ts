import { expect, test } from "@playwright/test";
import { app } from "../../../app.config.ts";

// PLAN T-06: the page text generated from app.config.ts exists before JavaScript runs (crawlers,
// seo-geo §4) and stays visible to people after load, below the tool, with exactly one h1.

/** Text as it appears in HTML source (the generator escapes &, <, > and "). */
function asHtml(text: string): string {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

test("raw HTML (no JavaScript) has the h1, the answer sentence, the steps and every FAQ question", async ({ request }) => {
  const response = await request.get("./");
  expect(response.status()).toBe(200);
  const html = await response.text();
  expect(html.match(/<h1\b/g)).toHaveLength(1);
  expect(html).toMatch(/<h1[^>]*>GG Counter<\/h1>/);
  expect(html).toContain(asHtml(app.answer));
  for (const step of app.steps) expect(html).toContain(asHtml(step));
  for (const item of app.faq) expect(html).toContain(`>${asHtml(item.q)}</summary>`);
  expect(html).toContain(`<link rel="canonical" href="${app.url}" />`);
  expect(html).toContain('<html lang="en"');
});

test("the rendered page has exactly one h1, and the FAQ below the tool equals the FAQ JSON-LD", async ({ page }) => {
  await page.goto("./");
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("GG Counter");
  await expect(page.locator("h1")).toHaveCount(1);
  await expect(page.locator("[data-page-info]")).toHaveCount(0);

  const summaries = page.locator("main details > summary");
  await expect(summaries).toHaveText(app.faq.map((item) => item.q));
  await expect(page.locator("main").getByText(app.answer)).toBeVisible();
  for (const step of app.steps) await expect(page.locator("main ol").getByText(step)).toBeVisible();

  // The FAQ sits below the scoring tool: after the Leaderboard card.
  const leaderboardBottom = await page.getByRole("heading", { name: "Leaderboard" }).evaluate((h) => h.getBoundingClientRect().bottom);
  const faqTop = await summaries.first().evaluate((s) => s.getBoundingClientRect().top);
  expect(faqTop).toBeGreaterThan(leaderboardBottom);

  const jsonLd = await page.locator('script[type="application/ld+json"]').textContent();
  // because the JSON-LD shape is generated by scripts/seo.ts; the test reads only the questions
  const items = JSON.parse(jsonLd ?? "[]") as { "@type": string; mainEntity?: { name: string }[] }[];
  const faqPage = items.find((item) => item["@type"] === "FAQPage");
  expect(faqPage?.mainEntity?.map((question) => question.name)).toEqual(await summaries.allTextContents());

  // An answer opens on tap and the header keeps one h1 when it turns compact on scroll.
  await summaries.last().click();
  await expect(page.getByText(app.faq.at(-1)?.a ?? "")).toBeVisible();
  await page.evaluate(() => { window.scrollTo(0, document.body.scrollHeight); });
  await expect(page.locator("h1")).toHaveCount(1);
});

test("search and agent files are served; an unknown path gets the 404 page", async ({ request }) => {
  for (const file of ["sitemap.xml", "llms.txt", "robots.txt", "og-image.png"]) {
    expect((await request.get(`./${file}`)).status(), file).toBe(200);
  }
  expect(await (await request.get("./sitemap.xml")).text()).toContain(`<loc>${app.url}</loc>`);
  const missing = await request.get("./no-such-page/");
  expect(missing.status()).toBe(404);
  const notFound = await missing.text();
  expect(notFound).toContain('<meta name="robots" content="noindex" />');
  expect(notFound).toContain("Open GG Counter");
});
